def reduce_to_arcana(val: int) -> int:
    """
    Приведення числа до діапазону 1–22.
    Якщо число більше 22 — складаємо цифри, доки результат не буде <= 22.
    """
    if val <= 0:
        return 22
    while val > 22:
        val = sum(int(d) for d in str(val))
    return val if val != 0 else 22


def calculate_base_arcana(day: int) -> int:
    """
    Базовий Аркан особистості (день народження):
    Якщо день <= 22 — це сам день.
    Якщо день > 22 — додаємо цифри дня (наприклад: 23 -> 5, 29 -> 11, 31 -> 4).
    """
    if day <= 22:
        return day
    return reduce_to_arcana(day)


def calculate_soul_arcana(day: int, month: int, year: int) -> int:
    """
    Аркан душі та стосунків (сума всіх цифр дати народження).
    Д + Д + М + М + Р + Р + Р + Р, зведена до 1–22.
    """
    date_digits = f"{day:02d}{month:02d}{year:04d}"
    digit_sum = sum(int(d) for d in date_digits)
    return reduce_to_arcana(digit_sum)


def calculate_compatibility_arcana(base1: int, base2: int) -> int:
    """
    Аркан пари: сума базових Арканів партнерів, зведена до 1–22.
    """
    return reduce_to_arcana(base1 + base2)


def get_arcana_info(arcana_num: int) -> Dict[str, str]:
    """Повертає інформацію про Аркан."""
    num = reduce_to_arcana(arcana_num)
    return MAJOR_ARCANA.get(num, MAJOR_ARCANA[22])
