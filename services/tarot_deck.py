class TarotDeck:
    def __init__(self, assets_dir: str = "assets/cards"):
        self.assets_dir = assets_dir
        self.all_cards = []
        self._build_deck()

    def _build_deck(self):
        # Старші
        for cid, name, up, rev in MAJOR_CARDS:
            self.all_cards.append({
                "id": cid,
                "name_ua": name,
                "suit": "Старший Аркан",
                "upright": up,
                "reversed": rev
            })

        # Молодші
        for s_ua, s_code, _ in SUITS:
            for r_ua, r_code, up, rev in MINOR_RANKS:
                cid = f"{s_code}_{r_code}"
                name = f"{r_ua} {s_ua}"
                self.all_cards.append({
                    "id": cid,
                    "name_ua": name,
                    "suit": s_ua,
                    "upright": up,
                    "reversed": rev
                })

    def draw_spread(self, count: int = 3, allow_reversed: bool = True) -> List[DrawnCard]:
        """
        Тягне 3 унікальні карти з колоди з позиціями:
        1 — Суть / основа ситуації
        2 — Приховане / внутрішній мотив
        3 — Вектор / до чого все йде
        """
        chosen_raw = random.sample(self.all_cards, count)
        positions = [
            "Основа ситуації (те, що відбувається зараз)",
            "Прихований мотив (те, про що він мовчить або що приховано)",
            "Вектор розвитку (куди веде ситуація і яка порада)"
        ]

        result = []
        for i, raw in enumerate(chosen_raw):
            is_reversed = random.random() < 0.28 if allow_reversed else False
            keywords = raw["reversed"] if is_reversed else raw["upright"]

            # Перевіряємо локальний файл зображення
            img_candidate = os.path.join(self.assets_dir, f"{raw['id']}.jpg")
            img_path = img_candidate if os.path.isfile(img_candidate) else None

            result.append(DrawnCard(
                id=raw["id"],
                name_ua=raw["name_ua"],
                suit=raw["suit"],
                is_reversed=is_reversed,
                position_title=positions[i] if i < len(positions) else f"Позиція {i+1}",
                keywords=keywords,
                image_path=img_path
            ))

        return result


