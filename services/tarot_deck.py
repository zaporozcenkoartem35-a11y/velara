@dataclass
class DrawnCard:
    id: str
    name_ua: str
    suit: str
    is_reversed: bool
    position_title: str
    keywords: str
    image_path: Optional[str] = None

    @property
    def display_name(self) -> str:
        state = " (перевернута)" if self.is_reversed else ""
        return f"{self.name_ua}{state}"


